// Generates the four legal pages from the client's UPDATED Webflow copy.
//
// WHY FOUR AND NOT TWO
// --------------------
// The two offices are separate legal entities, and each has its own Terms and
// its own Privacy Policy on the Webflow build:
//
//   McLean      Esam Abou Nahlah, DDS, MS, PLLC        7901 Jones Branch Dr., Suite 220
//   Alexandria  Implants And Prosthodontics Specialists, PLLC   2855 Duke St
//
// The documents are ~97% identical, and it is tempting to merge them into one
// page each. That would misstate which entity governs which office, so they stay
// four. Same rule as always on this site: the legal WORDING is carried over
// verbatim and is not ours to rewrite; only the structure and typography are new.
//
// This copy (Effective Date: 18 August 2026) SUPERSEDES the old WordPress terms
// the local build carried, and in doing so closes all three defects flagged on
// those pages: the PatientPop copyright assignment, the unattributed notices
// number, and the bulletin-board boilerplate describing features that do not
// exist.
//
// The Webflow source marks its section headings as fully-bold paragraphs rather
// than headings, so the extractor promotes `<p><strong>…</strong></p>` to <h2>.
// That is a semantics fix, not a copy change.
//
//   node gen-legal.mjs            # writes the four page bodies
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const SRC = path.dirname(fileURLToPath(import.meta.url));
const DATA = path.resolve(SRC, "..", "legal-blocks.json");

const esc = (s) => s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
/** House rule: no em dash in copy, anywhere (SYSTEM_RULES §3). */
const nodash = (s) => s.replace(/\s*—\s*/g, ", ");

const PAGES = {
  "terms-of-service-maclean": {
    kind: "Terms of Service", office: "McLean", other: "terms-of-service-alexandria",
    otherOffice: "Alexandria", h1: "Terms of <em>service</em>.", crumb: "Terms of Service, McLean",
    hero: "office-wide.jpeg", heroAlt: "The practice's treatment floor",
  },
  "terms-of-service-alexandria": {
    kind: "Terms of Service", office: "Alexandria", other: "terms-of-service-maclean",
    otherOffice: "McLean", h1: "Terms of <em>service</em>.", crumb: "Terms of Service, Alexandria",
    hero: "office-wide.jpeg", heroAlt: "The practice's treatment floor",
  },
  "privacy-policy-maclean": {
    kind: "Privacy Policy", office: "McLean", other: "privacy-policy-alexandria",
    otherOffice: "Alexandria", h1: "Privacy <em>statement</em>.", crumb: "Privacy Policy, McLean",
    hero: "office-hero.jpg", heroAlt: "The reception and waiting area",
  },
  "privacy-policy-alexandria": {
    kind: "Privacy Policy", office: "Alexandria", other: "privacy-policy-maclean",
    otherOffice: "McLean", h1: "Privacy <em>statement</em>.", crumb: "Privacy Policy, Alexandria",
    hero: "office-hero.jpg", heroAlt: "The reception and waiting area",
  },
};

const blocks = JSON.parse(fs.readFileSync(DATA, "utf8"));

/** Group the flat block run into sections, each opened by a heading. */
function sections(list) {
  const out = [];
  let cur = null;
  for (const b of list) {
    if (b.kind === "head") {
      cur = { head: b.text, body: [] };
      out.push(cur);
    } else if (cur) {
      cur.body.push(b);
    } else {
      out.push({ head: null, body: [b] });
      cur = out[out.length - 1];
    }
  }
  return out;
}

for (const [slug, cfg] of Object.entries(PAGES)) {
  const list = blocks[slug];
  if (!list) throw new Error(`no extracted blocks for ${slug}`);
  const secs = sections(list);

  // The first "section" is the document title plus the effective date and the
  // opening paragraphs; it becomes the lede rather than an <h2> repeating <h1>.
  const lede = secs.shift();
  const effective = (lede.body.find((b) => /^Effective Date/i.test(b.text)) || {}).text || "";
  const intro = lede.body.filter((b) => !/^Effective Date/i.test(b.text));

  const body = secs.map((s) => {
    const inner = s.body
      .map((b) => b.kind === "li"
        ? `          <li>${esc(nodash(b.text))}</li>`
        : `        <p>${esc(nodash(b.text))}</p>`)
      .join("\n");
    // consecutive <li> need a list around them
    const wrapped = inner.replace(
      /((?:^ {10}<li>.*$\n?)+)/gm,
      (m) => `        <ul>\n${m.replace(/\n$/, "")}\n        </ul>\n`);
    return `      <section>\n        <h2>${esc(nodash(s.head || ""))}</h2>\n${wrapped}      </section>`;
  }).join("\n\n");

  const page = `<!-- ==========================================================================
     ${cfg.kind.toUpperCase()}, ${cfg.office.toUpperCase()} OFFICE.

     GENERATED by gen-legal.mjs from the client's updated Webflow build
     (/${slug}), effective 18 August 2026. Do not hand-edit: re-run the
     generator against a fresh fetch instead.

     The two offices are SEPARATE LEGAL ENTITIES, which is why this document has
     an Alexandria counterpart rather than one shared page. The wording is the
     client's and is carried over verbatim; only structure and typography are
     ours. The Webflow source marks headings as bold paragraphs, so they are
     promoted to <h2> here, which is a semantics fix and not a copy change.
     ========================================================================== -->
<section class="pg-hero" id="hero">
  <div class="ph-bg">
    <img src="assets/${cfg.hero}" alt="${cfg.heroAlt}" data-drift>
  </div>
  <div class="wrap ph-in">
    <div class="pk-crumb" data-rv><a href="index.html">Home</a><i></i><span>${cfg.crumb}</span></div>
    <h1 data-split>${cfg.h1}</h1>
    <p class="ph-lead" data-rv>${esc(nodash(intro[0] ? intro[0].text : ""))}</p>
    <div class="ph-actions" data-rv>
      <a class="btn btn-ghost magnetic" href="#document"><span>Read the ${cfg.kind.toLowerCase()}</span></a>
    </div>
  </div>
</section>

<section class="pk pk-alt" id="document">
  <div class="wrap section">
    <div class="lg-body">
      <p class="lg-intro" data-rv>${esc(effective)}. This document governs the
        ${cfg.office} office. The ${cfg.otherOffice} office is operated by a separate entity and has
        <a href="${cfg.other}.html">its own ${cfg.kind.toLowerCase()}</a>.</p>

${intro.slice(1).map((b) => `      <p>${esc(nodash(b.text))}</p>`).join("\n")}

${body}
    </div>
  </div>
</section>
`;
  fs.writeFileSync(path.join(SRC, "pages", `${slug}.body.html`), page);
  console.log(`${slug.padEnd(30)} ${secs.length} sections, ${page.length} chars`);
}
