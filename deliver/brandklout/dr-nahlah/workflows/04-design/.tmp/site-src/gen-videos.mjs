// Generates pages/video-library.body.html from videos.json.
//
// The old site published /video-gallery/ as "Dental Group of Tyson Video
// Library" — a leftover practice name from whoever built it, on a page whose
// only real content was fourteen YouTube embeds. The films themselves are the
// asset: all fourteen are on the practice's own channel and all fourteen still
// resolve (checked via oembed). The page is rebuilt around them and renamed,
// because "Dental Group of Tyson" is not this practice.
//
// THE FIRST FILM IS A REAL EMBED ON PURPOSE, not just for the layout. Instatic
// composes its per-page CSP from module contributions: `frame-src` is lifted
// only when a page actually renders a YouTube node, and a page without one
// keeps `frame-src 'none'`. The other thirteen are click-to-play facades, so
// the page ships one iframe instead of fourteen, and the facades are only
// allowed to swap themselves in because that first real embed opened the
// directive. Drop it and the whole grid dies on that platform.
//
//   node gen-videos.mjs
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const SRC = path.dirname(fileURLToPath(import.meta.url));
const videos = JSON.parse(fs.readFileSync(path.resolve(SRC, "..", "videos.json"), "utf8"));
const esc = (s) => s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");

const [lead, ...rest] = videos;

const facade = (v) => `        <button class="vl-card" type="button" data-yt="${v.id}"
                aria-label="Play: ${esc(v.title)}">
          <span class="vl-shot">
            <img src="${v.thumb}" alt="" loading="lazy" width="480" height="360"${v.zoom !== 1 ? ` style="--vl-zoom:${v.zoom}"` : ""}>
            <span class="vl-play" aria-hidden="true"></span>
          </span>
          <span class="vl-title">${esc(v.title)}</span>
        </button>`;

const page = `<!-- ==========================================================================
     VIDEO LIBRARY — the fourteen films the practice publishes on its own
     YouTube channel, previously at drnahlah.com/video-gallery/.

     GENERATED by gen-videos.mjs. Do not hand-edit; edit videos.json and re-run.

     Two things about the source page are deliberately NOT carried over. It was
     headed "Dental Group of Tyson Video Library", which is a different practice
     name left in by whoever built it, and its <h1> was "Patient Testimonials",
     which these films are not: they are Dr. Nahlah explaining procedures. The
     patient testimonials live on patient-stories.html.

     ACCURACY, WORTH THE CLIENT'S ATTENTION: only the six films that carry
     maxresdefault are the practice's own, shot in the office with Dr. Nahlah and
     his branding. The other eight are an older set featuring a GENERIC PRESENTER
     against a white backdrop, and they are not him. The copy on this page
     therefore never says "Dr. Nahlah explains", except on the lead film where it
     is true. Worth asking whether the client wants the older eight kept at all.

     Only the first film is a real iframe. The rest are click-to-play facades,
     which keeps the page at one embed instead of fourteen AND is what lets
     Instatic serve it at all: that platform lifts CSP frame-src only for a page
     that renders a real YouTube node. See gen-videos.mjs.
     ========================================================================== -->
<section class="pg-hero" id="hero" style="min-height:clamp(420px,54svh,580px)">
  <div class="ph-bg">
    <img src="assets/tech-hero.jpg" alt="The scanning suite at the practice" data-drift>
  </div>
  <div class="wrap ph-in">
    <div class="pk-crumb" data-rv><a href="index.html">Home</a><i></i><span>Video Library</span></div>
    <h1 data-split>The procedures, <em>explained</em>.</h1>
    <p class="ph-lead" data-rv>Fourteen short films from the practice's own channel: what each
      treatment involves, why it is planned the way it is, and what the technology actually
      changes.</p>
    <div class="ph-actions" data-rv>
      <a class="btn btn-primary magnetic" href="contact.html#book"><span>Book a consultation</span></a>
      <a class="btn btn-ghost magnetic" href="patient-stories.html"><span>Hear from patients</span></a>
    </div>
  </div>
</section>

<section class="pk" id="library">
  <div class="wrap section">
    <div class="pk-head">
      <div class="chapter-tag" data-rv><i></i><span class="label">Filmed at the practice</span></div>
      <h2 data-split>${esc(lead.title)}</h2>
    </div>

    <figure class="vl-lead" data-rv>
      <div class="vl-frame">
        <iframe src="https://www.youtube.com/embed/${lead.id}" loading="lazy"
                title="${esc(lead.title)}"
                allow="accelerometer; autoplay; clipboard-write; encrypted-media; gyroscope; picture-in-picture"
                referrerpolicy="strict-origin-when-cross-origin" allowfullscreen></iframe>
      </div>
      <figcaption>Filmed at the practice, with Dr. Nahlah.</figcaption>
    </figure>
  </div>
</section>

<section class="pk pk-alt" id="films">
  <div class="wrap section">
    <div class="pk-head">
      <div class="chapter-tag" data-rv><i></i><span class="label">The library</span></div>
      <h2 data-split>Thirteen more, by subject.</h2>
      <p data-rv>Each one opens where it sits. Nothing autoplays, and nothing loads until you
        ask for it.</p>
    </div>

    <div class="vl-grid" data-rv="stagger">
${rest.map(facade).join("\n")}
    </div>

    <p class="vl-note" data-rv>Prefer to talk it through in person? A consultation includes the 3D
      scan and a straight answer about what your case needs.
      <a class="pk-more" href="contact.html#book">Book a consultation</a></p>
  </div>
</section>
`;

fs.writeFileSync(path.join(SRC, "pages", "video-library.body.html"), page);
console.log(`video-library.body.html: 1 embed + ${rest.length} facades, ${page.length} chars`);
