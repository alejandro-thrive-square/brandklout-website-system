"""Build INDEX.md + a consolidated manifest from the screenshots actually on disk.

Run after capture.mjs. Reads the desktop/ and mobile/ folders directly rather than
trusting any single capture-manifest, because fix-up re-runs overwrite the manifest
they write into.

Usage: python build_index.py
"""

from __future__ import annotations

import json
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
SITE = "https://www.lakenonadentist.com"


def unslug(name: str) -> str:
    """desktop file stem -> source URL path."""
    stem = re.sub(r"\.p\d+$", "", name)
    stem = re.sub(r"\.mobile$", "", stem)
    if stem == "home":
        return "/"
    return "/" + stem.replace("__", "/")


def collect(folder: Path) -> dict[str, list[Path]]:
    groups: dict[str, list[Path]] = {}
    for f in sorted(folder.glob("*.jpg")):
        key = unslug(f.stem)
        groups.setdefault(key, []).append(f)
    return groups


def main() -> None:
    desktop = collect(HERE / "desktop")
    mobile = collect(HERE / "mobile")

    all_urls = [u.strip() for u in (HERE / "urls.txt").read_text(encoding="utf-8").splitlines() if u.strip()]
    expected = ["/" if u.rstrip("/") == SITE else u.replace(SITE, "") for u in all_urls]

    rows = []
    for path in expected:
        d = desktop.get(path, [])
        m = mobile.get(path, [])
        rows.append({
            "path": path,
            "desktop": [f.name for f in d],
            "mobile": [f.name for f in m],
            "desktop_kb": sum(f.stat().st_size for f in d) // 1024,
            "mobile_kb": sum(f.stat().st_size for f in m) // 1024,
        })

    missing = [r["path"] for r in rows if not r["desktop"]]
    total_kb = sum(r["desktop_kb"] + r["mobile_kb"] for r in rows)

    (HERE / "capture-manifest.json").write_text(
        json.dumps({
            "reference_site": SITE,
            "desktop_viewport": "1440x900",
            "mobile_viewport": "390x844",
            "pages_expected": len(expected),
            "pages_captured_desktop": len(expected) - len(missing),
            "pages_captured_mobile": sum(1 for r in rows if r["mobile"]),
            "missing_desktop": missing,
            "total_mb": round(total_kb / 1024, 1),
            "pages": rows,
        }, indent=2),
        encoding="utf-8",
    )

    lines = [
        "# Screenshot Index — lakenonadentist.com",
        "",
        "Generated by `build_index.py` from the files on disk. Screenshots are gitignored",
        "binary media (synced to VPS via rclone); this index is committed so the set is",
        "auditable without the binaries present.",
        "",
        f"- **Desktop captured**: {len(expected) - len(missing)} / {len(expected)} pages @ 1440x900",
        f"- **Mobile captured**: {sum(1 for r in rows if r['mobile'])} pages @ 390x844",
        f"- **Total size**: {round(total_kb / 1024, 1)} MB",
        "",
        "Pages taller than 15000px are split into `.p1` / `.p2` segments (Chrome cannot",
        "capture a single image past roughly that height).",
        "",
        "| Page | Desktop | Mobile |",
        "| :--- | :--- | :--- |",
    ]
    for r in rows:
        d = "<br>".join(f"`{n}`" for n in r["desktop"]) or "—"
        m = "<br>".join(f"`{n}`" for n in r["mobile"]) or "—"
        lines.append(f"| `{r['path']}` | {d} | {m} |")

    if missing:
        lines += ["", "## Missing desktop captures", ""] + [f"- `{p}`" for p in missing]

    (HERE / "INDEX.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"desktop {len(expected) - len(missing)}/{len(expected)}, "
          f"mobile {sum(1 for r in rows if r['mobile'])}, {round(total_kb / 1024, 1)} MB")
    if missing:
        print("MISSING:", missing)


if __name__ == "__main__":
    main()
