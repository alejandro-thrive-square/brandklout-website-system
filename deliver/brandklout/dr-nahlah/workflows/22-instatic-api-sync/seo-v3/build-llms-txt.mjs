#!/usr/bin/env node
/**
 * SEO v3: /llms.txt (llmstxt.org) for drnahlah.com, from the same facts the schema uses:
 * seo-v3/out/organization.json (offices, phones, hours), seo-v2/meta.json (every page's title and
 * description), seo-v3/post-descriptions.json (the Journal), out/sections.json (page headings).
 * Patches the drnahlah-seo Worker (14-migration-seo-redirects/.tmp/out/sitemap-worker.js) to serve
 * it, and sets every sitemap <lastmod> to the date given (the structured data of every page changed).
 *
 *   node seo-v3/build-llms-txt.mjs [--lastmod 2026-10-06]   → out/llms.txt + the patched worker
 * Then: 14-migration-seo-redirects/deploy-worker.mjs --apply --script-only, and bind
 * www.drnahlah.com/llms.txt* to drnahlah-seo in the dashboard (no token we hold can bind a route).
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { join, dirname } from 'node:path'

const HERE = dirname(fileURLToPath(import.meta.url))
const S = 'https://www.drnahlah.com'
const org = JSON.parse(readFileSync(join(HERE, 'out', 'organization.json'), 'utf8'))
const meta = JSON.parse(readFileSync(join(HERE, '..', 'seo-v2', 'meta.json'), 'utf8'))
const posts = JSON.parse(readFileSync(join(HERE, 'post-descriptions.json'), 'utf8'))
const pages = JSON.parse(readFileSync(join(HERE, 'out', 'sections.json'), 'utf8'))
const li = process.argv.indexOf('--lastmod')
const LASTMOD = li > 0 ? process.argv[li + 1] : new Date().toISOString().slice(0, 10)

const url = (slug) => (slug === 'index' ? `${S}/` : `${S}/${slug}`)
const title = (slug) => meta[slug][0].replace(/\s*\|\s*Dr\. Nahlah.*$/, '').replace(/\s*\|.*$/, '')
const item = (slug) => `- [${title(slug)}](${url(slug)}): ${meta[slug][1]}`
const phone = (t) => t.replace(/^\+1-(\d{3})-(\d{3})-(\d{4})$/, '($1) $2-$3')
const hours = (o) => o.openingHoursSpecification.map((h) => `${[].concat(h.dayOfWeek).map((d) => d.slice(0, 3)).join(', ')} ${h.opens}-${h.closes}`).join('; ')

const GROUPS = [
  ['Treatments', ['dental-implants', 'all-on-4', 'implant-supported-dentures', 'crowns-and-bridges', 'veneers', 'teeth-whitening', 'smile-makeover', 'cosmetic-dentistry', 'oral-surgery', 'sedation-dentistry', 'emergency-dentistry', 'dental-conditions']],
  ['Cost, insurance and guarantees', ['implant-cost', 'financing', 'five-year-warranty', 'dental-implant-faq']],
  ['The practice', ['meet-dr-nahlah', 'about', 'our-team', 'our-facility', 'patient-center', 'smile-gallery', 'patient-stories', 'video-library', 'doctor-referral']],
  ['Contact', ['contact', 'contact-mclean', 'contact-alexandria']],
]
for (const [, slugs] of GROUPS) for (const s of slugs) if (!meta[s]) throw new Error('no meta for ' + s)

const offices = org.department.map((o) => [
  `- **${o.name.replace(/^.*Specialists, /, '')}**: ${o.address.streetAddress}, ${o.address.addressLocality}, VA ${o.address.postalCode}.`,
  `  ${o.contactPoint.map((c) => `${c.contactType[0].toUpperCase()}${c.contactType.slice(1)}: ${phone(c.telephone)}`).join('. ')}. Hours: ${hours(o)}. [Office page](${o.url})`,
].join('\n')).join('\n')

const txt = `# ${org.name}

> ${org.description}

- Specialist: Dr. Esam Nahlah, DDS, MS, board-certified prosthodontist (Diplomate, American Board of Prosthodontics; Fellow, American College of Prosthodontists), adjunct faculty in the Virginia Commonwealth University Prosthodontics Postgraduate Program. [Profile](${S}/meet-dr-nahlah)
- Sedation offered: nitrous oxide and oral sedation only. The practice does not offer IV sedation or general anesthesia.
- Free second opinions on implant surgery. A five-year warranty on implant and cosmetic work, conditional on six-monthly Precare cleanings.
- Payment: ${org.paymentAccepted}.

## Offices

${offices}

${GROUPS.map(([h, slugs]) => `## ${h}\n\n${slugs.map(item).join('\n')}`).join('\n\n')}

## Journal

${Object.entries(posts).map(([slug, d]) => `- [${pages['posts/' + slug]?.post?.h1 || slug}](${S}/posts/${slug}): ${d}`).join('\n')}

## Optional

${[['privacy-policy', 'Privacy Policy'], ['terms-conditions', 'Terms of Service'], ['hipaa-disclosure', 'HIPAA Notice of Privacy Practices']].map(([s, n]) => `- [${n}](${url(s)})`).join('\n')}
`
writeFileSync(join(HERE, 'out', 'llms.txt'), txt)
console.log('llms.txt', txt.length, 'bytes,', txt.split('\n').filter((l) => l.startsWith('- [')).length, 'links')

// ── the Worker ──────────────────────────────────────────────────────────────
const W = join(HERE, '..', '..', '14-migration-seo-redirects', '.tmp', 'out', 'sitemap-worker.js')
let w = readFileSync(W, 'utf8')
const body = '`' + txt.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${') + '`'
const block = `/* /llms.txt (llmstxt.org), GENERATED by 22-instatic-api-sync/seo-v3/build-llms-txt.mjs. */\nconst LLMS = ${body}\n`
if (w.includes('const LLMS = ')) w = w.replace(/\/\* \/llms\.txt[\s\S]*?\nconst LLMS = `[\s\S]*?`\n/, block)
else w = w.replace('const send = ', block + '\nconst send = ')
if (!w.includes("pathname === '/llms.txt'")) w = w.replace("    if (pathname === '/robots.txt')", "    if (pathname === '/llms.txt') return send(LLMS, 'text/plain; charset=utf-8')\n    if (pathname === '/robots.txt')")
w = w.replace(' * Routes (deploy-worker.mjs): www.drnahlah.com/sitemap.xml*, /robots.txt*.', ' * Routes (deploy-worker.mjs): www.drnahlah.com/sitemap.xml*, /robots.txt*, /llms.txt*.')
const n = (w.match(/<lastmod>[^<]+<\/lastmod>/g) || []).length
w = w.replace(/<lastmod>[^<]+<\/lastmod>/g, `<lastmod>${LASTMOD}</lastmod>`)
writeFileSync(W, w)
console.log(`worker patched: /llms.txt served, ${n} lastmod -> ${LASTMOD}`)
