#!/usr/bin/env node
/**
 * Upload the 301 map as a Cloudflare Bulk Redirect list, then activate it.
 *
 *   node deploy-redirects.mjs            # dry run
 *   node deploy-redirects.mjs --apply
 *
 * TWO OBJECTS, NOT ONE. A Bulk Redirect *list* holds the URL pairs and does
 * nothing on its own; an account-level Bulk Redirect *rule* in the
 * `http_request_redirect` phase is what actually makes traffic follow it. Every
 * "I uploaded the CSV and nothing happened" is the second half missing.
 *
 * The rule write is a PUT to the phase entrypoint, which REPLACES every rule in
 * that phase account-wide — and this account carries seven client zones. So the
 * existing rules are read first and carried through untouched; only a rule
 * already pointing at THIS list is replaced.
 */
import { readFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { cf, accountId } from './cf-api.mjs'

const HERE = dirname(fileURLToPath(import.meta.url))
const LIST_NAME = 'drnahlah_301'
const APPLY = process.argv.includes('--apply')

const csv = readFileSync(join(HERE, '.tmp', 'out', 'drnahlah-cloudflare-301.csv'), 'utf8')
  .trim().split(/\r?\n/)

const bool = (v) => String(v).toUpperCase() === 'TRUE'
const items = csv.map((line) => {
  const [source_url, target_url, status_code, pqs, isub, sub, pps] = line.split(',')
  return {
    redirect: {
      source_url,
      target_url,
      status_code: Number(status_code),
      preserve_query_string: bool(pqs),
      include_subdomains: bool(isub),
      subpath_matching: bool(sub),
      preserve_path_suffix: bool(pps),
    },
  }
})

/* Nothing in this file may touch another client's domain. */
const stray = items.filter((i) => !/^drnahlah\.com\//.test(i.redirect.source_url)
  || !i.redirect.target_url.startsWith('https://www.drnahlah.com/'))
if (stray.length) {
  console.error(`refusing: ${stray.length} row(s) are not drnahlah.com`)
  console.error(stray.slice(0, 5).map((s) => s.redirect.source_url).join('\n'))
  process.exit(1)
}

const acct = await accountId()
console.log(`account ${acct}`)
console.log(`list    ${LIST_NAME} — ${items.length} redirects`)
console.log(`sample  ${items[0].redirect.source_url} -> ${items[0].redirect.target_url}`)
const subpaths = items.filter((i) => i.redirect.subpath_matching).length
console.log(`        ${subpaths} subpath-matching, ${items.length - subpaths} exact`)

if (!APPLY) { console.log('\nDRY RUN — re-run with --apply'); process.exit(0) }

// ── the list ───────────────────────────────────────────────────────────────

const lists = await cf('GET', `/accounts/${acct}/rules/lists`)
let list = lists.find((l) => l.name === LIST_NAME)
if (list) {
  console.log(`\nlist exists (${list.id}, ${list.num_items} items) — replacing its items`)
} else {
  list = await cf('POST', `/accounts/${acct}/rules/lists`, {
    name: LIST_NAME, kind: 'redirect',
    description: 'WordPress -> Instatic 301 map for drnahlah.com. Generated by build_cloudflare.mjs.',
  })
  console.log(`\nlist created ${list.id}`)
}

/* PUT replaces the whole item set, which is what makes a re-run idempotent
   rather than additive. It is async — Cloudflare returns an operation to poll. */
const op = await cf('PUT', `/accounts/${acct}/rules/lists/${list.id}/items`, items)
process.stdout.write('uploading items')
for (let i = 0; i < 60; i++) {
  const status = await cf('GET', `/accounts/${acct}/rules/lists/bulk_operations/${op.operation_id}`)
  if (status.status === 'completed') { console.log(' — completed'); break }
  if (status.status === 'failed') { console.log('') ; throw new Error(`item upload failed: ${status.error}`) }
  process.stdout.write('.')
  await new Promise((r) => setTimeout(r, 1000))
}
const after = await cf('GET', `/accounts/${acct}/rules/lists/${list.id}`)
console.log(`list now holds ${after.num_items} redirects`)

// ── the rule that activates it ─────────────────────────────────────────────

let entrypoint
try {
  entrypoint = await cf('GET', `/accounts/${acct}/rulesets/phases/http_request_redirect/entrypoint`)
} catch {
  entrypoint = { rules: [] }
}
const keep = (entrypoint.rules ?? []).filter(
  (r) => r.action_parameters?.from_list?.name !== LIST_NAME,
)
console.log(`\nexisting rules in this phase: ${(entrypoint.rules ?? []).length} (${keep.length} unrelated, carried through)`)

const rule = {
  expression: 'http.request.full_uri in $' + LIST_NAME,
  description: 'drnahlah.com WordPress -> Instatic 301 map',
  action: 'redirect',
  action_parameters: { from_list: { name: LIST_NAME, key: 'http.request.full_uri' } },
  enabled: true,
}
const updated = await cf('PUT', `/accounts/${acct}/rulesets/phases/http_request_redirect/entrypoint`, {
  rules: [...keep, rule],
})
console.log(`rule active — ruleset ${updated.id}, ${updated.rules.length} rule(s) in phase`)
console.log('\nVerify with: node verify-live.mjs')
