#!/usr/bin/env node
/**
 * Build the med spa's /sitemap.xml and the Worker that serves it.
 *
 *   node build-sitemap.mjs     # -> .tmp/out/sitemap.xml, .tmp/out/sitemap-worker.js
 *
 * Instatic serves no sitemap (no route, no setting), so the file is served at the
 * Cloudflare edge by a Worker bound to /sitemap.xml only — module 19's pattern, on the
 * `bk-dr-nahlah` branch as deliver/process/19-cloudflare-launch/. This site has no old
 * platform, so there is no 301 map and none of that module's redirect machinery.
 *
 * The live instance is the only authority: pages come from the production admin API, and
 * every URL must answer 200 on the canonical host or nothing is written.
 */
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const HERE = dirname(fileURLToPath(import.meta.url))
const OUT = join(HERE, '.tmp', 'out')

/* The apex is the canonical host: it is RAILWAY_PUBLIC_DOMAIN, the admin URL in sites.json
   and the `origin` in seo.json. www serves the same site with 200 (no redirect yet). */
export const CANONICAL = 'https://westlaketxmedspa.com'

/* Pages that exist but must not be submitted. `thank-you` is the booking confirmation —
   an empty landing for a form nobody should arrive at from search. */
const EXCLUDE = new Set(['thank-you'])

function loadEnv() {
  let dir = HERE
  while (true) {
    const f = join(dir, '.env')
    if (existsSync(f)) {
      for (const line of readFileSync(f, 'utf8').split(/\r?\n/)) {
        const m = line.match(/^([A-Z_][A-Z0-9_]*)=(.*)$/)
        if (m && !process.env[m[1]]) process.env[m[1]] = m[2].trim().replace(/^["']|["']$/g, '')
      }
      return
    }
    const up = dirname(dir)
    if (up === dir) throw new Error('no .env found above ' + HERE)
    dir = up
  }
}

loadEnv()
const BASE = process.env.INSTATIC_BASE_URL || CANONICAL

const login = await fetch(BASE + '/admin/api/cms/login', {
  method: 'POST',
  headers: { 'content-type': 'application/json', origin: BASE },
  body: JSON.stringify({ email: process.env.INSTATIC_EMAIL, password: process.env.INSTATIC_PASSWORD }),
})
if (!login.ok) throw new Error(`login ${login.status}`)
const cookie = login.headers.getSetCookie().map((c) => c.split(';')[0]).find((c) => /=/.test(c) && !/^__cf/.test(c))
const res = await fetch(BASE + '/admin/api/cms/pages', { headers: { cookie, origin: BASE } })
if (!res.ok) throw new Error(`pages ${res.status}`)
const { rows } = await res.json()

const pages = rows.filter((p) => !p.templated && !EXCLUDE.has(p.slug))
const skipped = rows.filter((p) => !pages.includes(p)).map((p) => p.slug)

const entries = pages.map((p) => ({
  path: p.slug === 'index' ? '/' : `/${p.slug}`,
  lastmod: String(p.publishedAt || p.updatedAt || '').slice(0, 10),
})).sort((a, b) => (a.path === '/' ? -1 : b.path === '/' ? 1 : a.path.localeCompare(b.path)))

// Every URL must be live on the canonical host, or the sitemap submits a dead page.
const dead = []
for (const e of entries) {
  const r = await fetch(CANONICAL + e.path, { redirect: 'manual' })
  if (r.status !== 200) dead.push(`${e.path} ${r.status}`)
}
if (dead.length) {
  console.error(`not 200 on ${CANONICAL} — refusing to write:\n  ${dead.join('\n  ')}`)
  process.exit(1)
}

const esc = (s) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
const sitemap = [
  '<?xml version="1.0" encoding="UTF-8"?>',
  '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">',
  ...entries.map((e) => [
    '  <url>',
    `    <loc>${esc(CANONICAL + e.path)}</loc>`,
    e.lastmod ? `    <lastmod>${e.lastmod}</lastmod>` : null,
    '  </url>',
  ].filter(Boolean).join('\n')),
  '</urlset>',
  '',
].join('\n')

/* The XML is embedded with JSON.stringify, not a template literal, so no character in a
   page slug can break the Worker source. Only /sitemap.xml is routed here: a Worker on
   /robots.txt replaces Cloudflare's edge-generated content-signals file (module 19, trap 1). */
const worker = `/**
 * Serves /sitemap.xml for westlaketxmedspa.com (apex and www).
 *
 * GENERATED by stone-med-spa/workflows/06-cloudflare-sitemap/build-sitemap.mjs — do not
 * hand-edit. Rebuild and redeploy whenever a page is added, removed or renamed.
 */
const SITEMAP = ${JSON.stringify(sitemap)}

export default {
  async fetch(request) {
    if (new URL(request.url).pathname === '/sitemap.xml') {
      return new Response(SITEMAP, {
        headers: { 'content-type': 'application/xml; charset=utf-8', 'cache-control': 'public, max-age=3600' },
      })
    }
    return fetch(request)
  },
}
`

mkdirSync(OUT, { recursive: true })
writeFileSync(join(OUT, 'sitemap.xml'), sitemap)
writeFileSync(join(OUT, 'sitemap-worker.js'), worker)

console.log(`pages on the instance: ${rows.length}; skipped: ${skipped.join(', ') || 'none'}`)
console.log(`sitemap.xml: ${entries.length} <url> entries, all 200 on ${CANONICAL}`)
for (const e of entries) console.log(`  ${e.path}  ${e.lastmod}`)
console.log(`wrote ${OUT}`)
