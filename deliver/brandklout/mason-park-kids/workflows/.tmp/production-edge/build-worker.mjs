// Generates worker.js - the edge in front of masonparkpediatricdental.com (production, from 2026-09-24).
//   node build-worker.mjs      after `python build-map.py`
//
// The Worker, on routes masonparkpediatricdental.com/* and www.masonparkpediatricdental.com/*:
//   1. www -> the apex, 301, path and query kept (the apex is the canonical host).
//   2. /robots.txt and /sitemap.xml, which Instatic does not serve (404 before the launch).
//   3. the old WordPress URLs (redirects.json) -> their new paths, 301.
//   4. everything else goes to the origin untouched: fetch(request).
// Instatic has no redirect table, and Cloudflare Redirect Rules cannot be written with the
// agency's account-owned API token, hence a Worker. Routes are set to fail OPEN, so a Workers
// outage or quota falls through to the site instead of an error page.
import fs from 'node:fs';
const redirects = JSON.parse(fs.readFileSync('redirects.json', 'utf8'));
const routes = JSON.parse(fs.readFileSync('routes.json', 'utf8'));
const APEX = 'https://masonparkpediatricdental.com';
const today = new Date().toISOString().slice(0, 10);
const sitemap = `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n` +
  routes.map(r => `  <url><loc>${APEX}${r}</loc><lastmod>${today}</lastmod></url>`).join('\n') + `\n</urlset>\n`;
const robots = `User-agent: *\nAllow: /\nDisallow: /admin\n\nSitemap: ${APEX}/sitemap.xml\n`;

const src = `// GENERATED by build-worker.mjs from redirects.json and routes.json - edit those, not this.
// masonparkpediatricdental.com edge: www -> apex, robots.txt, sitemap.xml, old WordPress URLs -> new.
const APEX = ${JSON.stringify(APEX)};
const REDIRECTS = ${JSON.stringify(redirects)};
const SITEMAP = ${JSON.stringify(sitemap)};
const ROBOTS = ${JSON.stringify(robots)};
const moved = (to) => new Response(null, { status: 301, headers: { Location: to, 'Cache-Control': 'public, max-age=3600' } });
export default {
  async fetch(request) {
    const url = new URL(request.url);
    if (url.hostname.startsWith('www.')) return moved(APEX + url.pathname + url.search);
    const path = url.pathname.toLowerCase();
    if (path === '/robots.txt') return new Response(ROBOTS, { headers: { 'Content-Type': 'text/plain; charset=utf-8', 'Cache-Control': 'public, max-age=3600' } });
    if (path === '/sitemap.xml') return new Response(SITEMAP, { headers: { 'Content-Type': 'application/xml; charset=utf-8', 'Cache-Control': 'public, max-age=3600' } });
    const key = path.endsWith('/') ? path : path + '/';
    if (REDIRECTS[key]) return moved(APEX + REDIRECTS[key] + url.search);
    return fetch(request);
  },
};
`;
fs.writeFileSync('worker.js', src);
console.log(`worker.js: ${Object.keys(redirects).length} redirects, ${routes.length} sitemap urls, ${src.length} bytes`);
