import { spawn } from 'node:child_process';
import { existsSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
const HERE = fileURLToPath(new URL('.', import.meta.url));
const DESIGN = resolve(HERE, '../../04-design/.tmp/v1');
const page = process.argv[2] || 'emergency';
const expr = process.argv[3];
const CHROME = ['C:/Program Files/Google/Chrome/Application/chrome.exe','C:/Program Files (x86)/Google/Chrome/Application/chrome.exe'].find(p=>existsSync(p));
const PORT = 9200 + (process.pid % 700);
const wait = ms => new Promise(r=>setTimeout(r,ms));
const proc = spawn(CHROME,[`--remote-debugging-port=${PORT}`,'--user-data-dir='+join(HERE,'.chrome-probe'),'--no-first-run','--no-default-browser-check','--allow-file-access-from-files','--window-size=1440,900','--window-position=-2400,0','about:blank'],{stdio:'ignore'});
let wsUrl; for(let i=0;i<60;i++){try{const r=await fetch(`http://127.0.0.1:${PORT}/json/version`);if(r.ok){wsUrl=(await r.json()).webSocketDebuggerUrl;break;}}catch{} await wait(400);}
const ws=new WebSocket(wsUrl); await new Promise((res,rej)=>{ws.onopen=res;ws.onerror=rej;});
let id=0; const pend=new Map();
ws.onmessage=ev=>{const m=JSON.parse(ev.data); if(m.id&&pend.has(m.id)){const{res,rej}=pend.get(m.id);pend.delete(m.id);m.error?rej(new Error(m.error.message)):res(m.result);}};
const send=(method,params={},sessionId)=>{const i=++id;ws.send(JSON.stringify({id:i,method,params,sessionId}));return new Promise((res,rej)=>pend.set(i,{res,rej}));};
const {targetId}=await send('Target.createTarget',{url:'about:blank'});
const {sessionId}=await send('Target.attachToTarget',{targetId,flatten:true});
await send('Runtime.enable',{},sessionId);
await send('Emulation.setDeviceMetricsOverride',{width:1440,height:900,deviceScaleFactor:1,mobile:false},sessionId);
await send('Page.navigate',{url:pathToFileURL(join(DESIGN,page,'index.html')).href},sessionId);
await wait(2500);
const r=await send('Runtime.evaluate',{expression:expr,returnByValue:true,awaitPromise:true},sessionId);
console.log(JSON.stringify(r.exceptionDetails ? r.exceptionDetails.text : r.result.value, null, 1));
ws.close(); proc.kill();
