// home/hipaa-disclosure/index.html from home/privacy-policy/index.html: the same head, header,
// arrival, invitation and footer, with "The Short Version" and the policy accordion replaced by the
// HIPAA notice (notice.mjs). Re-runnable; the privacy page is the template, so edit that page or
// notice.mjs, never the output.
//   node .tmp/hipaa/build-hipaa-page.mjs
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { noticeHtml, TITLE, DESCRIPTION, SLUG, EFFECTIVE_HOUSE } from "./notice.mjs";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const HOME = path.join(HERE, "..", "..", "home");
let html = fs.readFileSync(path.join(HOME, "privacy-policy", "index.html"), "utf8");

const once = (from, to) => {
  const n = typeof from === "string" ? html.split(from).length - 1 : (html.match(new RegExp(from.source, from.flags.includes("g") ? from.flags : from.flags + "g")) ?? []).length;
  if (n !== 1) throw new Error(`expected one match, found ${n}: ${String(from).slice(0, 80)}`);
  html = html.replace(from, to);
};
const enc = (s) => s.replaceAll("&", "&amp;").replaceAll("\"", "&quot;");

// head
once("<title>Privacy Policy | Mason Park Dental of Katy</title>", `<title>${TITLE}</title>`);
once(/<meta name="description" content="[^"]*">/, `<meta name="description" content="${enc(DESCRIPTION)}">`);
once('<link rel="canonical" href="https://bestdentistinkatytx.com/privacy-policy/">', `<link rel="canonical" href="https://bestdentistinkatytx.com/${SLUG}/">`);
once('<meta property="og:title" content="Privacy Policy | Mason Park Dental of Katy">', `<meta property="og:title" content="${TITLE}">`);
once(/<meta property="og:description" content="[^"]*">/, `<meta property="og:description" content="${enc(DESCRIPTION)}">`);
once('<meta property="og:url" content="https://bestdentistinkatytx.com/privacy-policy/">', `<meta property="og:url" content="https://bestdentistinkatytx.com/${SLUG}/">`);
once('{"@type":"ListItem","position":2,"name":"Privacy Policy","item":"https://bestdentistinkatytx.com/privacy-policy/"}', `{"@type":"ListItem","position":2,"name":"HIPAA Disclosure","item":"https://bestdentistinkatytx.com/${SLUG}/"}`);

// arrival + breadcrumb
once('<h1 class="ar-title" data-split>Privacy <em>Policy</em></h1>', '<h1 class="ar-title" data-split>HIPAA <em>Disclosure</em></h1>');
once(/<p class="ar-lede" data-anim="hide">[^<]*<\/p>/, `<p class="ar-lede" data-anim="hide">Effective ${EFFECTIVE_HOUSE}. Our Notice of Privacy Practices: how your health information may be used and shared, and your rights over it.</p>`);
once('<a class="button is-lg" href="#sections">Read the policy</a>', '<a class="button is-lg" href="#notice">Read the notice</a>');
once('<span class="breadcrumb_item">Privacy Policy</span>', '<span class="breadcrumb_item">HIPAA Disclosure</span>');

// the body: from the Short Version's comment to the end of the policy section
const start = html.indexOf("<!-- THE SHORT VERSION.");
const policy = html.indexOf('<section class="ch ch-questions" id="sections"');
const end = html.indexOf("</section>", policy) + "</section>".length;
if (start < 0 || policy < start || end < policy) throw new Error("privacy page body markers moved");
const eol = html.includes("\r\n") ? "\r\n" : "\n";
const body = [
  "<!-- THE NOTICE. The HHS model Notice of Privacy Practices, as the agency's Webflow sites carry",
  "     it at /hipaa-disclosure, with this practice's entity, contact block and effective date.",
  "     Generated by .tmp/hipaa/build-hipaa-page.mjs (notice.mjs); do not hand-edit. -->",
  '<section class="ch ch-questions" id="notice" data-chapter="1" data-chapter-name="The Notice">',
  '  <div class="wrap rg-head">',
  '    <p class="chapter-tag"><i></i><b>The Notice</b></p>',
  "    <h2 data-split>Notice of Privacy Practices, in full.</h2>",
  "  </div>",
  '  <div class="wrap iv-faq">',
  `    <div class="lf-body text-rich-text">${noticeHtml()}</div>`,
  "  </div>",
  "</section>",
].join(eol);
html = html.slice(0, start) + body + html.slice(end);

// invitation
once('<section class="ch ch-invitation" id="invitation" data-chapter="3"', '<section class="ch ch-invitation" id="invitation" data-chapter="2"');
once(/<p class="iv-lede">To ask about this policy[^<]*<\/p>/, '<p class="iv-lede">To ask about this notice, get a copy of your record, or make a request under it, call the office.</p>');
once("<dt>Effective date</dt><dd>25 September 2026</dd>", `<dt>Effective date</dt><dd>${EFFECTIVE_HOUSE}</dd>`);

const out = path.join(HOME, SLUG, "index.html");
fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, html, "utf8");
console.log(`wrote ${path.relative(path.join(HOME, ".."), out)} (${html.length} bytes)`);
