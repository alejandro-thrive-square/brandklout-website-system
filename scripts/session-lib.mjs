/**
 * session-lib.mjs — shared helpers for the session rotation rule.
 *
 * See SYSTEM_RULES.md §5 "Session Rotation". The rule: a session that reaches
 * CONTEXT_LIMIT tokens hands off to a fresh one through a runbook, rather than being
 * resumed or compacted. Resuming a 200k session pays for that context on every
 * subsequent turn; a runbook costs a few thousand tokens once.
 */

import { readFileSync, existsSync, mkdirSync, writeFileSync, statSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { execFileSync } from 'node:child_process';

/**
 * Hand off at 200k. Warn early enough that the agent can finish its thought first.
 * Overridable by env so the thresholds can be tuned, and tested, without editing code.
 */
const envInt = (name, fallback) => {
  const n = Number.parseInt(process.env[name] ?? '', 10);
  return Number.isFinite(n) && n > 0 ? n : fallback;
};
export const CONTEXT_LIMIT = envInt('WEBZITE_CONTEXT_LIMIT', 200_000);
export const CONTEXT_WARN = envInt('WEBZITE_CONTEXT_WARN', 150_000);

/** A runbook older than this many turns is stale and must be refreshed before handoff. */
export const RUNBOOK_MAX_AGE_MS = 45 * 60 * 1000;

export const runbookPath = (cwd) => join(cwd, '.claude', 'RUNBOOK.md');
export const statePath = (cwd) => join(cwd, '.claude', 'session-state.json');

/** Read the hook payload from stdin. Hooks are always fed JSON; be forgiving anyway. */
export function readHookInput() {
  let raw = '';
  try {
    raw = readFileSync(0, 'utf8');
  } catch {
    return {};
  }
  try {
    return JSON.parse(raw || '{}');
  } catch {
    return {};
  }
}

/**
 * Live context size, read from the transcript rather than estimated.
 *
 * Every assistant message records the usage that produced it, and for a cached
 * conversation the live context is input + cache_creation + cache_read — the cache
 * fields are the bulk of it, so counting input_tokens alone under-reports by ~100x.
 *
 * The LAST such message, not the peak. A compact or a fork genuinely shrinks the
 * window, and measuring the peak would leave a session that had already compacted
 * permanently above the threshold, rotating on every turn forever.
 *
 * Subagent turns are logged into the same transcript with isSidechain: true. Their
 * usage belongs to the subagent's own context window, not this one, so they are
 * skipped — otherwise a single wide fan-out reads as a full main context.
 */
export function contextTokens(transcriptPath) {
  if (!transcriptPath || !existsSync(transcriptPath)) return 0;
  let last = 0;
  for (const line of readFileSync(transcriptPath, 'utf8').split('\n')) {
    if (!line.trim()) continue;
    let d;
    try {
      d = JSON.parse(line);
    } catch {
      continue;
    }
    if (d.isSidechain) continue;
    if (d.type !== 'assistant') continue;
    const u = d.message?.usage;
    if (!u) continue;
    last =
      (u.input_tokens ?? 0) +
      (u.cache_creation_input_tokens ?? 0) +
      (u.cache_read_input_tokens ?? 0) +
      (u.output_tokens ?? 0);
  }
  return last;
}

export function git(cwd, args) {
  try {
    return execFileSync('git', args, { cwd, encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] }).trim();
  } catch {
    return '';
  }
}

/** Uncommitted work is the one thing a handoff cannot carry. Rotation must not lose it. */
export function isDirty(cwd) {
  return git(cwd, ['status', '--porcelain', '--untracked-files=no']).length > 0;
}

export function readState(cwd) {
  const p = statePath(cwd);
  if (!existsSync(p)) return {};
  try {
    return JSON.parse(readFileSync(p, 'utf8'));
  } catch {
    return {};
  }
}

export function writeState(cwd, patch) {
  const p = statePath(cwd);
  mkdirSync(dirname(p), { recursive: true });
  const next = { ...readState(cwd), ...patch };
  writeFileSync(p, JSON.stringify(next, null, 2) + '\n', 'utf8');
  return next;
}

export function runbookAgeMs(cwd) {
  const p = runbookPath(cwd);
  if (!existsSync(p)) return Infinity;
  return Date.now() - statSync(p).mtimeMs;
}

/**
 * The mechanical half of the runbook — branch, HEAD, recent commits, dirty files.
 * Regenerated on every write so it can never drift from reality; the agent owns the
 * narrative half below it.
 */
export function mechanicalSection(cwd, tokens) {
  const branch = git(cwd, ['rev-parse', '--abbrev-ref', 'HEAD']) || '(unknown)';
  const head = git(cwd, ['rev-parse', '--short', 'HEAD']) || '(unknown)';
  const commits = git(cwd, ['log', '--oneline', '-8']) || '(none)';
  const dirty = git(cwd, ['status', '--short']) || '(clean)';
  const stamp = new Date().toISOString().replace('T', ' ').slice(0, 16) + 'Z';
  return [
    '<!-- AUTO:BEGIN — regenerated by scripts/session-guard.mjs. Do not hand-edit. -->',
    `- **Worktree**: \`${cwd}\``,
    `- **Branch**: \`${branch}\` at \`${head}\``,
    `- **Context at handoff**: ~${tokens.toLocaleString('en-US')} tokens`,
    `- **Refreshed**: ${stamp}`,
    '',
    '**Recent commits**',
    '```',
    commits,
    '```',
    '',
    '**Uncommitted**',
    '```',
    dirty,
    '```',
    '<!-- AUTO:END -->',
  ].join('\n');
}

/** Replace only the auto block, preserving whatever the agent wrote underneath it. */
export function refreshRunbook(cwd, tokens) {
  const p = runbookPath(cwd);
  const auto = mechanicalSection(cwd, tokens);
  if (!existsSync(p)) return false;
  const cur = readFileSync(p, 'utf8');
  const next = cur.includes('<!-- AUTO:BEGIN')
    ? cur.replace(/<!-- AUTO:BEGIN[\s\S]*?<!-- AUTO:END -->/, auto)
    : auto + '\n\n' + cur;
  writeFileSync(p, next, 'utf8');
  return true;
}

export const TEMPLATE = (cwd, tokens) => `# Runbook — session handoff

${mechanicalSection(cwd, tokens)}

## Objective
<!-- The one thing this worktree is for. One or two sentences. -->

## Done
<!-- Completed and verified, each with the commit SHA that carries it. -->

## In progress
<!-- What is half-finished right now, and exactly where it stopped. -->

## Next
<!-- Ordered. The first line should be directly actionable by a session with no memory. -->

## Gotchas
<!-- Things that cost time this session and would cost it again: failed approaches,
     environment quirks, false leads. This is the highest-value section - it is the
     part a fresh session cannot rediscover from the code. -->

## Open questions
<!-- Blocked on a human or an external party. Name who and what. -->
`;
