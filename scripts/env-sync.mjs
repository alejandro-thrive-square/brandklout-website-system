#!/usr/bin/env node
/**
 * Resolve the ONE master credential file into this worktree's .env.
 *
 * The master lives OUTSIDE every repo and worktree — `~/.webzite/.env` by
 * default, `WEBZITE_ENV_MASTER` to override. It is the only file anyone edits.
 * It is sectioned:
 *
 *     [aliases]
 *     bk-ifa-dentistry = institute-for-advanced-dentistry
 *
 *     [shared]                 # account-wide, every worktree gets these
 *     INSTATIC_EMAIL=...
 *
 *     [mason-park]             # one section per client, named for the client folder
 *     INSTATIC_BASE_URL=...
 *
 * A worktree's .env is then a GENERATED artifact: [shared] merged with the one
 * client section that matches this worktree, section winning on a clash. It is
 * rewritten on every `npm install`, which is Orca's per-worktree setup hook, so
 * a rotated credential reaches every worktree by editing the master and nothing
 * else.
 *
 * WHY GENERATE A FILE instead of having scripts read the master directly: four
 * different loaders already walk up to a repo-root `.env`
 * (instatic-embeds/lib/insta-api.mjs, instatic-embeds.py,
 * instatic-api-sync/insta-api.mjs, mason-park's live-qa.mjs), and agents write
 * throwaway .mjs that does the same naive thing. Generating the file they
 * already expect means none of them change and none of them can forget.
 *
 * WHY SECTIONS AND NOT ONE FLAT FILE: `INSTATIC_BASE_URL` differs per client and
 * the shared Instatic toolkit deliberately refuses to guess it — a flat file
 * with several of them would resolve first-match and publish one client's
 * plugin to another client's site. A missing section fails loudly instead.
 *
 * Usage:
 *   node scripts/env-sync.mjs [options]
 *
 *   --check        Report what would be written (key NAMES only) and exit.
 *   --section <s>  Force a section instead of deriving one.
 *   --force        Overwrite a .env that was not generated by this tool.
 *                  Always backs the old file up first.
 *   --quiet        Only speak up on a change or a problem.
 *
 * This tool never prints a credential value.
 */

import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { execFileSync } from "node:child_process";

const MARKER = "# GENERATED by scripts/env-sync.mjs — DO NOT EDIT.";
const SHARED = "shared";
const ALIASES = "aliases";
// Definitions that exist to be referenced as ${NAME}, never written to a .env.
// This is how one value gets a name of its own without being copied: two
// Instatic instances that happen to share an admin password are two named
// entries here, and each client section points at the one it uses.
const VARS = "vars";
const RESERVED = new Set([SHARED, ALIASES, VARS]);

const argv = process.argv.slice(2);
const opt = {
  check: argv.includes("--check"),
  force: argv.includes("--force"),
  quiet: argv.includes("--quiet"),
  section: argv.includes("--section") ? argv[argv.indexOf("--section") + 1] : null,
};

const say = (msg) => {
  if (!opt.quiet) console.log(msg);
};

function masterPath() {
  if (process.env.WEBZITE_ENV_MASTER) return process.env.WEBZITE_ENV_MASTER;
  return path.join(os.homedir(), ".webzite", ".env");
}

/** Parse the sectioned master. Returns { sections: Map<name, Map<key,value>>, order: [] }. */
function parseMaster(text) {
  const sections = new Map();
  const order = [];
  let current = SHARED;
  let lineNo = 0;
  for (const rawLine of text.split(/\r?\n/)) {
    lineNo += 1;
    const line = rawLine.trim();
    if (!line || line.startsWith("#") || line.startsWith(";")) continue;

    const header = line.match(/^\[\s*([^\]]+?)\s*\]$/);
    if (header) {
      current = header[1].toLowerCase();
      if (!sections.has(current)) {
        sections.set(current, new Map());
        order.push(current);
      }
      continue;
    }

    // [aliases] keys are worktree names, which carry hyphens; env var names do
    // not. Using the env-var pattern everywhere silently dropped every alias.
    const keyPattern = current === ALIASES ? /^([A-Za-z0-9_.-]+)\s*=\s*(.*)$/ : /^([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.*)$/;
    const kv = line.match(keyPattern);
    if (!kv) {
      console.error(`env-sync: ${masterPath()}:${lineNo} is neither a [section] nor KEY=VALUE — ignored.`);
      continue;
    }
    if (!sections.has(current)) {
      sections.set(current, new Map());
      order.push(current);
    }
    // Strip one layer of matching quotes; keep everything else verbatim, since
    // tokens legitimately contain '=', '#' and punctuation.
    let value = kv[2].trim();
    if (
      value.length >= 2 &&
      ((value.startsWith('"') && value.endsWith('"')) || (value.startsWith("'") && value.endsWith("'")))
    ) {
      value = value.slice(1, -1);
    }
    sections.get(current).set(kv[1], value);
  }
  return { sections, order };
}

function git(args, cwd) {
  try {
    return execFileSync("git", args, { cwd, encoding: "utf8" }).trim();
  } catch {
    return "";
  }
}

/**
 * Which client section does this worktree want? Same derivation the sparsify
 * script and the post-checkout hook use, for the same reason: Orca names the
 * branch <git-username>/bk-<slug>, so the raw branch is never a clean match,
 * and the worktree DIRECTORY name is exactly what was typed into Orca.
 */
function resolveSection(sections, here) {
  if (opt.section) return opt.section.toLowerCase();

  const branch = git(["rev-parse", "--abbrev-ref", "HEAD"], here);
  const seeds = [path.basename(here), branch.split("/").pop() || ""].filter(Boolean);

  const aliases = sections.get(ALIASES) ?? new Map();
  const aliasLookup = new Map([...aliases].map(([k, v]) => [k.toLowerCase(), v.toLowerCase()]));

  const isClientSection = (name) => !RESERVED.has(name) && sections.has(name);

  for (const seed of seeds) {
    const lower = seed.toLowerCase();
    // 1. An explicit alias always wins — that is what it is for.
    if (aliasLookup.has(lower)) return aliasLookup.get(lower);

    let candidate = lower.replace(/^bk-/, "");
    if (aliasLookup.has(candidate)) return aliasLookup.get(candidate);

    // 2. Exact section name.
    if (isClientSection(candidate)) return candidate;

    // 3. Prefix match, trimming one -segment at a time, longest first, so
    //    `grand-mission` cannot be stolen by a shorter sibling.
    while (candidate) {
      const hits = [...sections.keys()].filter((n) => isClientSection(n) && n.startsWith(candidate));
      if (hits.length === 1) return hits[0];
      if (hits.length > 1) {
        console.error(
          `env-sync: '${candidate}' matches ${hits.length} sections: ${hits.join(", ")}\n` +
            `  Resolve it once and for all by adding to the master's [aliases] section:\n` +
            `      ${path.basename(here)} = <the section you mean>`,
        );
        return null;
      }
      if (!candidate.includes("-")) break;
      candidate = candidate.slice(0, candidate.lastIndexOf("-"));
    }
  }
  return null;
}

/**
 * Expand ${NAME} references. NAME is looked up in [vars] first, then the
 * resolved output itself, so a client section can point at a named definition
 * without that definition leaking into every worktree's .env.
 *
 * An unknown reference is a hard error: silently emitting a literal "${FOO}" as
 * a password would surface later as an authentication failure with no clue.
 */
function expand(vars, definitions) {
  const out = new Map();

  const resolve = (name, trail) => {
    if (trail.includes(name)) {
      throw new Error(`env-sync: circular reference \${${trail.concat(name).join("} -> ${")}}`);
    }
    const raw = definitions.has(name) ? definitions.get(name) : vars.get(name);
    if (raw === undefined) return undefined;
    return substitute(raw, trail.concat(name));
  };

  const substitute = (value, trail) =>
    value.replace(/\$\{([A-Za-z_][A-Za-z0-9_]*)\}/g, (whole, name) => {
      const resolved = resolve(name, trail);
      if (resolved === undefined) {
        throw new Error(
          `env-sync: ${whole} is not defined in [vars] or [shared] — referenced by ` +
            `${trail[trail.length - 1] ?? "a section"}.`,
        );
      }
      return resolved;
    });

  for (const [k, v] of vars) {
    out.set(k, substitute(v, [k]));
  }
  return out;
}

function render(vars, { section, master }) {
  const lines = [
    MARKER,
    `# Source: ${master}`,
    `# Section: [shared]${section ? ` + [${section}]` : " only (main worktree — no client)"}`,
    "#",
    "# Edit the MASTER, then re-run `npm install` here (or `node scripts/env-sync.mjs`).",
    "# Anything you type into this file is lost on the next sync.",
    "",
  ];
  for (const [k, v] of vars) lines.push(`${k}=${v}`);
  lines.push("");
  return lines.join("\n");
}

function main() {
  const master = masterPath();
  if (!fs.existsSync(master)) {
    say(
      `env-sync: no master credential file at ${master} — nothing to sync.\n` +
        `  Create it, or point WEBZITE_ENV_MASTER at one. See SYSTEM_RULES.md §4.2.2.`,
    );
    return 0;
  }

  const here = git(["rev-parse", "--show-toplevel"], process.cwd());
  if (!here) {
    console.error("env-sync: not inside a git worktree.");
    return 1;
  }

  const { sections } = parseMaster(fs.readFileSync(master, "utf8"));
  const mainWorktree = git(["worktree", "list", "--porcelain"], here)
    .split(/\r?\n/)
    .find((l) => l.startsWith("worktree "))
    ?.slice(9);
  const isMain =
    mainWorktree && path.resolve(mainWorktree).toLowerCase() === path.resolve(here).toLowerCase();

  // The main worktree is not a client workspace; it gets the account-wide keys
  // and nothing else, so no client's site URL can leak into work done there.
  const section = isMain ? null : resolveSection(sections, here);

  if (!isMain && !section) {
    console.error(
      `env-sync: no master section matches '${path.basename(here)}'.\n` +
        `  Add a section to ${master}, or map it in [aliases]. Known sections: ` +
        [...sections.keys()].filter((n) => n !== SHARED && n !== ALIASES).join(", "),
    );
    return 1;
  }

  const raw = new Map(sections.get(SHARED) ?? []);
  if (section) for (const [k, v] of sections.get(section) ?? []) raw.set(k, v);

  let vars;
  try {
    vars = expand(raw, sections.get(VARS) ?? new Map());
  } catch (err) {
    console.error(err.message);
    return 1;
  }

  const target = path.join(here, ".env");
  const next = render(vars, { section, master });

  if (opt.check) {
    console.log(`env-sync --check: ${target}`);
    console.log(`  section: [shared]${section ? ` + [${section}]` : " only"}`);
    console.log(`  keys   : ${[...vars.keys()].join(", ") || "(none)"}`);
    return 0;
  }

  if (fs.existsSync(target)) {
    const existing = fs.readFileSync(target, "utf8");
    if (existing === next) {
      say(`env-sync: ${target} already current ([shared]${section ? ` + [${section}]` : ""}).`);
      return 0;
    }
    if (!existing.startsWith(MARKER) && !opt.force) {
      console.error(
        `env-sync: ${target} was not generated by this tool and holds hand-written values.\n` +
          `  Refusing to overwrite. Fold anything it still has into the master, then re-run with --force.`,
      );
      return 1;
    }
    if (!existing.startsWith(MARKER)) {
      const stamp = new Date().toISOString().replace(/[:.]/g, "-");
      const backupDir = path.join(path.dirname(master), "backups", stamp);
      fs.mkdirSync(backupDir, { recursive: true });
      const backup = path.join(backupDir, `${path.basename(here)}.env`);
      fs.copyFileSync(target, backup);
      say(`env-sync: backed up the hand-written file to ${backup}`);
    }
  }

  fs.writeFileSync(target, next);
  say(
    `env-sync: wrote ${target} — [shared]${section ? ` + [${section}]` : " only"}, ` +
      `${vars.size} keys.`,
  );
  return 0;
}

process.exit(main());
